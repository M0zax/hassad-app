# EXPLAINING EACH DAY -- "why this field today?"
# ---------------------------------------------------------------------------

def _component_sizes(G, standing):
    if not standing:
        return []
    sub = G.subgraph(standing)
    return sorted(
        (sum(G.nodes[n]["area_ha"] for n in comp) for comp in nx.connected_components(sub)),
        reverse=True,
    )


def why_sentence(G, standing_before, field, lang="en"):
    """
    One plain sentence justifying a cut, derived from the fire graph itself.
    Deterministic and template-based: nothing here can hallucinate.
    """
    t = tpl(lang)
    block_before, ha_before = largest_standing_block(G, standing_before)
    standing_after = set(standing_before) - {field}
    _, ha_after = largest_standing_block(G, standing_after)
    area = G.nodes[field]["area_ha"]
    args = dict(f=field, area=f"{area:.1f}", before=f"{ha_before:.0f}", after=f"{ha_after:.0f}")

    if field in block_before:
        pieces = _component_sizes(G, block_before - {field})
        if len(pieces) >= 2:
            args["sizes"] = " + ".join(f"{p:.0f}" for p in pieces[:3])
            return t["why_bridge"].format(**args)
        return t["why_shrink"].format(**args)
    if ha_after < ha_before - 1e-9:
        return t["why_lower"].format(**args)
    return t["why_elsewhere"].format(**args)


def day_label(day, d, lang="en"):
    t = tpl(lang)
    return t["day_one"].format(d=day) if d == 1 else t["day_range"].format(a=day, b=day + d - 1)


def schedule_rows(G, order, first_day=1, harvested_before=(), lang="en"):
    """Turn an order into day-by-day rows with the largest-block numbers and a
    plain-language reason for each field."""
    standing = set(G.nodes) - set(harvested_before)
    rows, day = [], first_day
    for field in order:
        d = harvest_days(G.nodes[field]["area_ha"])
        _, ha_before = largest_standing_block(G, standing)
        reason = why_sentence(G, standing, field, lang)
        standing = standing - {field}
        _, ha_after = largest_standing_block(G, standing)
        rows.append({
            "Day": day_label(day, d, lang),
            "Field": field,
            "Hectares": round(G.nodes[field]["area_ha"], 1),
            "Days": d,
            "Largest block before (ha)": round(ha_before, 1),
            "Largest block after (ha)": round(ha_after, 1),
            "Why this field now": reason,
        })
        day += d
    return rows


# ---------------------------------------------------------------------------
# THE TWO OPERATIONS THE APP EXPOSES
# ---------------------------------------------------------------------------

def plan(selected, gap_rule=DEFAULT_GAP_RULE, balanced=False, fields=None, lang="en"):
    """One-tap plan: the provably best order for the selected fields."""
    threshold = GAP_RULES[gap_rule]
    chosen, G, matrix, index = build_world(selected, threshold, fields)

    if balanced:
        _, order = exact_weighted(G, matrix, index, w1=1.0, w2=TRAVEL_WEIGHT)
    else:
        _, order = exact_fire_only(G)

    optimal = simulate_season(order, G, matrix, index, label="Hassad (optimal)")
    naive = simulate_season(naive_largest_first(G), G, matrix, index,
                            label="largest field first")
    greedy = simulate_season(greedy_fire_only(G), G, matrix, index, label="greedy")
    pct = ((naive.fire_risk_score - optimal.fire_risk_score) / naive.fire_risk_score * 100
           if naive.fire_risk_score else 0.0)

    return {
        "fields": chosen, "G": G, "matrix": matrix, "index": index,
        "threshold": threshold, "balanced": balanced, "lang": lang,
        "order": order,
        "optimal": optimal, "naive": naive, "greedy": greedy,
        "pct_vs_naive": pct,
        "rows": schedule_rows(G, order, lang=lang),
        "harvested": [], "position": None, "done": False,
    }


def replan(previous, harvested, position=None, lang=None):
    """Mid-season update: the farmer marks what is already cut (in any order)
    and where the machine is; we re-solve the rest of the season."""
    lang = lang or previous.get("lang", "en")
    G, matrix, index = previous["G"], previous["matrix"], previous["index"]
    harvested = [h for h in harvested if h in G.nodes]
    w2 = TRAVEL_WEIGHT if previous["balanced"] else 0.0
    if position not in index:
        position = None
    result = reoptimize(G, matrix, index, harvested=harvested, position=position,
                        w1=1.0, w2=w2)
    remaining = set(G.nodes) - set(harvested)
    first_day = 1 + sum(harvest_days(G.nodes[h]["area_ha"]) for h in harvested)

    out = dict(previous)
    out.update({
        "order": result["order"], "lang": lang,
        "harvested": list(harvested), "position": position,
        "rows": schedule_rows(G, result["order"], first_day=first_day,
                              harvested_before=harvested, lang=lang),
        "remaining_fire_risk": result["fire_risk"],
        "remaining_travel_km": result["travel_km"],
        "done": not remaining,
    })
    if remaining and result["order"]:
        H = G.subgraph(remaining).copy()
        out["optimal"] = simulate_season(result["order"], H, matrix, index,
                                         label="Hassad (re-optimized)")
        out["naive"] = simulate_season(naive_largest_first(H), H, matrix, index,
                                       label="largest field first")
        out["greedy"] = simulate_season(greedy_fire_only(H), H, matrix, index,
                                        label="greedy")
        n, o = out["naive"].fire_risk_score, out["optimal"].fire_risk_score
        out["pct_vs_naive"] = (n - o) / n * 100 if n else 0.0
    return out


def relabel(plan_dict, lang):
    """Re-generate the farmer-facing sentences in another language without
    re-solving anything (the order and numbers do not depend on language)."""
    G = plan_dict["G"]
    harvested = plan_dict.get("harvested", [])
    first_day = 1 + sum(harvest_days(G.nodes[h]["area_ha"]) for h in harvested)
    out = dict(plan_dict)
    out["lang"] = lang
    out["rows"] = schedule_rows(G, plan_dict["order"], first_day=first_day,
                                harvested_before=harvested, lang=lang)
    return out


