@lru_cache(maxsize=1)
def all_fields():
    """The 11 traced Bekaa fields, loaded once."""
    return tuple(load_fields(verbose=False))


def field_names(fields=None):
    return [f.name for f in (fields if fields is not None else all_fields())]


def custom_fields_from_geojson(drawings):
    """
    Turn polygons drawn on the map (GeoJSON features from the Draw tool)
    into Field objects the whole pipeline understands.

    Each drawing becomes a field named 1, 2, 3... in drawing order. Tiny or
    invalid shapes (a mis-tap) are ignored. Returns a list of Field.
    """
    polys = []
    for feat in drawings or []:
        geom = (feat or {}).get("geometry") or {}
        if geom.get("type") != "Polygon" or not geom.get("coordinates"):
            continue
        ring = [(float(x), float(y)) for x, y, *_ in geom["coordinates"][0]]
        if len(ring) < 4:
            continue
        p = Polygon(ring)
        if not p.is_valid:
            p = p.buffer(0)
        if p.is_empty:
            continue
        polys.append(p)
    if not polys:
        return []

    ref_lon = sum(p.centroid.x for p in polys) / len(polys)
    ref_lat = sum(p.centroid.y for p in polys) / len(polys)
    project = make_projector(ref_lon, ref_lat)

    fields = []
    for name, p_ll in zip(CUSTOM_FIELD_NAMES, polys):
        p_m = Polygon([project(lon, lat) for lon, lat in p_ll.exterior.coords])
        if not p_m.is_valid:
            p_m = p_m.buffer(0)
        area_ha = p_m.area / 10_000.0
        if area_ha < 0.05:                   # smaller than a garden: a mis-tap
            continue
        c = p_m.centroid
        fields.append(Field(name=name, poly_m=p_m, poly_ll=p_ll,
                            area_ha=area_ha, cx=c.x, cy=c.y))
    return fields


def build_world(selected, threshold_m, fields=None):
    """Graph + distance matrix for just the fields the farmer selected."""
    pool = fields if fields is not None else all_fields()
    chosen = [f for f in pool if f.name in set(selected)]
    if not chosen:
        raise ValueError("select at least one field")
    G = build_adjacency_graph(chosen, threshold_m=threshold_m)
    matrix, index = distance_matrix_km(chosen)
    return chosen, G, matrix, index


