def whatsapp_text(rows, harvested=(), lang="en"):
    """The plan as a short message the cooperative leader forwards to the group."""
    t = tpl(lang)
    lines = [t["wa_title"]]
    if harvested:
        lines.append(t["wa_cut"].format(list=", ".join(harvested)))
    for r in rows:
        lines.append(t["wa_line"].format(day=r["Day"], f=r["Field"]))
    lines.append(t["wa_footer"])
    return "\n".join(lines)


def schedule_csv(rows):
    cols = ["Day", "Field", "Hectares", "Days", "Largest block before (ha)",
            "Largest block after (ha)", "Why this field now"]
    lines = [",".join(cols)]
    for r in rows:
        lines.append(",".join('"' + str(r[c]).replace('"', '""') + '"' for c in cols))
    return "\n".join(lines)


