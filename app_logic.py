def field_at(lat, lon, tolerance_m=25.0, fields=None):
    """Which field did the user tap? Point-in-polygon on the boundaries, with
    a small tolerance so a thumb landing just outside the edge still counts."""
    pool = fields if fields is not None else all_fields()
    p = Point(lon, lat)
    best, best_d = None, None
    for f in pool:
        if f.poly_ll.contains(p):
            return f.name
        d = f.poly_ll.exterior.distance(p) * 105_000     # degrees -> ~metres
        if d <= tolerance_m and (best_d is None or d < best_d):
            best, best_d = f.name, d
    return best


def fields_geojson(selected=(), harvested=(), today=None, rank=None, fields=None):
    """The fields as a GeoJSON FeatureCollection with a 'state' per feature."""
    pool = fields if fields is not None else all_fields()
    rank = rank or {}
    feats = []
    for f in pool:
        if f.name in set(harvested):
            state = "done"
        elif f.name == today:
            state = "today"
        elif f.name in set(selected):
            state = "mine"
        else:
            state = "other"
        feats.append({
            "type": "Feature",
            "properties": {"name": f.name, "area_ha": round(f.area_ha, 1),
                           "state": state, "rank": rank.get(f.name)},
            "geometry": {"type": "Polygon",
                         "coordinates": [list(map(list, f.poly_ll.exterior.coords))]},
        })
    return {"type": "FeatureCollection", "features": feats}


