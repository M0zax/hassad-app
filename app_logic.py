def economics(plan_dict):
    """
    Value at stake for the fields in the plan, the farmer's cost, and the
    honest version of "how much does this save?":

    We cannot claim money saved per season without an ignition probability,
    which nobody has measured. What the model DOES give exactly is the size of
    the burnable block a fire would find on a random day of the season -- the
    season-average largest connected block -- under the usual order versus
    this plan. The difference is hectares (and dollars) of crop that are no
    longer exposed PER FIRE EVENT. Multiply by whatever chance of a fire you
    believe in (the app exposes that as a slider) to get an expected saving.
    """
    G = plan_dict["G"]
    total_ha = sum(G.nodes[n]["area_ha"] for n in G.nodes)
    value_per_ha = WHEAT_YIELD_T_PER_HA * WHEAT_PRICE_USD_PER_T
    naive, opt = plan_dict.get("naive"), plan_dict.get("optimal")
    mean_naive = (naive.fire_risk_score / naive.season_days
                  if naive is not None and naive.season_days else 0.0)
    mean_plan = (opt.fire_risk_score / opt.season_days
                 if opt is not None and opt.season_days else 0.0)
    delta_ha = max(mean_naive - mean_plan, 0.0)
    return {
        "total_ha": total_ha,
        "value_usd": total_ha * value_per_ha,
        "value_per_ha_usd": value_per_ha,
        "farmer_cost_usd": FARMER_COST_USD,
        "yield_t_per_ha": WHEAT_YIELD_T_PER_HA,
        "price_usd_per_t": WHEAT_PRICE_USD_PER_T,
        "exposure_reduction_pct": plan_dict.get("pct_vs_naive", 0.0),
        "mean_block_naive_ha": mean_naive,
        "mean_block_plan_ha": mean_plan,
        "delta_ha_per_event": delta_ha,
        "delta_usd_per_event": delta_ha * value_per_ha,
    }


def expected_saving_usd(econ, chance_pct):
    """Expected saving per season = chance a fire reaches the fields x value
    no longer exposed per event. The chance is the user's assumption."""
    return econ["delta_usd_per_event"] * chance_pct / 100.0


# Which crops the same model applies to. Hassad needs two things of a crop:
# it must be FUEL while standing dry, and its harvest must remove that fuel.
# Anything irrigated and green at harvest time is a barrier, not fuel -- our
# June 2026 imagery showed two of our own fields behaving exactly like that.
CROP_NOTES = {
    "wheat":            "fuel -- the case we built and measured",
    "barley":           "fuel -- same season, same machines, same model",
    "oats / rye":       "fuel -- same as wheat",
    "lentils / chickpeas": "fuel when dry at harvest -- shorter, lighter fuel load",
    "sunflower":        "fuel late season -- stalks stay standing after seed harvest",
    "hay / dry pasture":"fuel -- cutting order of meadows works the same way",
    "potato / vegetables (irrigated)": "barrier -- green and wet at harvest; NOT fuel",
    "orchards / vines": "partial -- a mixed case; treat as barrier unless dry understorey",
}


